"""`TurnRequest` and `TurnResponse` - the two shapes the journey speaks (§8.3-8.4).

A turn is the whole protocol: the client sends what the customer did, the
backend decides everything and returns the complete next screen. There is no
second call to fetch the cards, and no state the client is trusted to keep.

**Validation is strict on purpose.** `extra="forbid"` plus enums plus length
limits means a malformed or hostile body is a 422 from Pydantic before any of
our code runs, which is the cheapest possible place to stop it (§13.5).
"""

from __future__ import annotations

import uuid
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.journey.cards import Card
from app.journey.states import AMOUNT_MAX_DEFAULT, AMOUNT_MIN_DEFAULT, Lang

# §8.3: a text turn is 1-500 characters. Long enough for a rambling spoken
# sentence, short enough that it cannot be used to stuff a prompt.
TEXT_MIN, TEXT_MAX = 1, 500

AMOUNT_MIN, AMOUNT_MAX = AMOUNT_MIN_DEFAULT, AMOUNT_MAX_DEFAULT


class StrictModel(BaseModel):
    model_config = ConfigDict(extra="forbid")


# --- actions -----------------------------------------------------------------
#
# One model per tap the UI can produce, discriminated on `name`. Modelling taps
# as a closed set rather than a free-form dict is what makes the engine's
# `match` exhaustive: a new button cannot reach the engine without a branch.


class SetLanguageAction(StrictModel):
    name: Literal["set_language"]
    language: Lang


class AmountAction(StrictModel):
    name: Literal["amount"]
    amount: Annotated[int, Field(ge=AMOUNT_MIN, le=AMOUNT_MAX)]


class ConsentGrants(StrictModel):
    """Both purposes are explicit - there is no "unspecified" consent."""

    fetch_digilocker: bool
    fetch_account_aggregator: bool


class ConsentsAction(StrictModel):
    name: Literal["consents"]
    grants: ConsentGrants


class ManualFormFields(StrictModel):
    fullName: Annotated[str, Field(min_length=2, max_length=100)]
    dob: Annotated[str, Field(pattern=r"^\d{4}-\d{2}-\d{2}$")]
    monthlyIncome: Annotated[int, Field(ge=1_000, le=10_000_000)]
    shopAddress: Annotated[str, Field(min_length=5, max_length=200)]
    mobile: Annotated[str, Field(pattern=r"^\d{10}$")]


class ManualFormAction(StrictModel):
    name: Literal["manual_form"]
    fields: ManualFormFields


class ConfirmEdits(StrictModel):
    shopAddress: Annotated[str, Field(min_length=5, max_length=200)] | None = None
    mobile: Annotated[str, Field(pattern=r"^\d{10}$")] | None = None


class ConfirmDetailsAction(StrictModel):
    name: Literal["confirm_details"]
    edits: ConfirmEdits | None = None


class SelectOfferAction(StrictModel):
    name: Literal["select_offer"]
    offerId: Annotated[str, Field(min_length=1, max_length=50)]


class QuizAnswerAction(StrictModel):
    name: Literal["quiz_answer"]
    questionId: Annotated[str, Field(min_length=1, max_length=60)]
    optionId: Annotated[str, Field(min_length=1, max_length=10)]


class InsuranceAddonAction(StrictModel):
    name: Literal["insurance_addon"]
    granted: bool


class AcceptTermsAction(StrictModel):
    """Carries no payload. What is being agreed to is the terms the *server*
    showed, read from the journey - never a copy the client sends back."""

    name: Literal["accept_terms"]


class RepeatAction(StrictModel):
    name: Literal["repeat"]


class DidntUnderstandAction(StrictModel):
    name: Literal["didnt_understand"]


class RequestHumanAction(StrictModel):
    name: Literal["request_human"]


Action = Annotated[
    SetLanguageAction
    | AmountAction
    | ConsentsAction
    | ManualFormAction
    | ConfirmDetailsAction
    | SelectOfferAction
    | QuizAnswerAction
    | InsuranceAddonAction
    | AcceptTermsAction
    | RepeatAction
    | DidntUnderstandAction
    | RequestHumanAction,
    Field(discriminator="name"),
]


# --- input -------------------------------------------------------------------


class TextInput(StrictModel):
    type: Literal["text"]
    text: Annotated[str, Field(min_length=TEXT_MIN, max_length=TEXT_MAX)]

    @field_validator("text")
    @classmethod
    def _strip(cls, value: str) -> str:
        """Trim, then reject whitespace-only: " " is not an utterance."""
        trimmed = value.strip()
        if not trimmed:
            raise ValueError("text cannot be blank")
        return trimmed


class TapInput(StrictModel):
    type: Literal["tap"]
    action: Action


TurnInput = Annotated[TextInput | TapInput, Field(discriminator="type")]


class TurnRequest(StrictModel):
    """One customer turn.

    `clientTurnId` is generated by the client and makes the call idempotent: a
    retry over a flaky tunnel replays the stored response instead of advancing
    the journey twice. `expectedVersion`, when sent, turns two racing taps into
    a 409 rather than a lost update.
    """

    clientTurnId: uuid.UUID
    expectedVersion: int | None = None
    input: TurnInput


# --- output ------------------------------------------------------------------


class Message(StrictModel):
    """One conversation bubble. `audioUrl` is relative (`/api/audio/<key>.mp3`)
    so the same payload works through localhost and through the tunnel."""

    id: str
    role: Literal["assistant", "user"]
    text: str
    audioUrl: str | None = None


class QuickReplySend(StrictModel):
    """What tapping a chip sends back. The chip label is for a human; this is
    the machine-readable half, so the backend controls both sides."""

    type: Literal["text", "tap"]
    text: str | None = None
    action: Action | None = None


class QuickReply(StrictModel):
    label: str
    send: QuickReplySend


class Locks(StrictModel):
    """Why the agree button is disabled, if it is.

    The client renders this; the backend also re-checks it when `accept_terms`
    arrives (§9), so the lock is a real gate and not a disabled button.
    """

    acceptEnabled: bool
    reason: str | None = None


class Progress(StrictModel):
    index: int
    total: Literal[6] = 6
    label: str
    etaSeconds: int


class TurnResponse(StrictModel):
    """The complete next screen.

    Returned by every journey route, including the first one, so the client has
    exactly one rendering path and no notion of "initial state".
    """

    journeyId: uuid.UUID
    version: int
    step: str
    status: Literal["active", "completed", "needs_human"]
    progress: Progress
    language: Lang
    messages: list[Message]
    card: Card | None = None
    quickReplies: list[QuickReply] = Field(default_factory=list)

    # Voice turns only: what we heard and in what language. Showing the
    # transcript back is how a customer catches a misheard amount before it
    # becomes a loan application.
    transcript: str | None = None
    detectedLanguage: Lang | None = None

    locks: Locks
    demoMode: bool
