"""Ed25519 receipt signatures (build plan §11.2).

The hash chain proves a receipt has not been edited *in place*. The signature
proves the receipt was issued by this backend at all - without it, anyone with
an INSERT on `receipts` could add a convincing row and recompute the chain
forward from it.

Ed25519 rather than RSA: 64-byte signatures, no parameter choices to get wrong,
and no padding mode to misconfigure. The private key lives in
`backend/secrets/` at mode 600 and is generated by `make keys`.

**Signing is over the chain hash, not the payload.** `sign(bytes.fromhex(hash))`
means the signature commits to the receipt *and* its position in the chain, so a
valid receipt cannot be lifted out and replayed at a different sequence number.
"""

from __future__ import annotations

import base64
import logging
from functools import lru_cache
from pathlib import Path

from nacl import signing
from nacl.exceptions import BadSignatureError

from app.config import Settings

log = logging.getLogger(__name__)


class SigningUnavailable(RuntimeError):
    """No private key on this machine.

    Raised rather than silently signing with a throwaway key: an unverifiable
    receipt that looks verifiable is worse than a loud failure, and `make keys`
    is one command.
    """


@lru_cache(maxsize=4)
def _load_private_key(path_str: str) -> signing.SigningKey:
    """Read and cache the 32-byte seed from disk.

    Cached because signing happens on the hot path of a completing journey and
    re-reading the file each time buys nothing. The cache is keyed on the path,
    so a rotated key picked up by a restart is honoured.
    """
    path = Path(path_str)
    if not path.is_file():
        raise SigningUnavailable(f"no signing key at {path}. Run `make keys` to generate one.")

    raw = path.read_bytes().strip()
    # `make keys` writes base64; a raw 32-byte file is accepted too so a key
    # restored by hand still works.
    try:
        seed = base64.b64decode(raw, validate=True)
    except Exception:  # noqa: BLE001 - any decode failure means "not base64"
        seed = raw

    if len(seed) != 32:
        raise SigningUnavailable(
            f"signing key at {path} is {len(seed)} bytes, expected a 32-byte seed"
        )
    return signing.SigningKey(seed)


def sign_hash(hash_hex: str, settings: Settings) -> tuple[str, str]:
    """Sign a chain hash. Returns `(signature_b64, key_id)`."""
    key = _load_private_key(str(settings.signing_key_file))
    signature = key.sign(bytes.fromhex(hash_hex)).signature
    return base64.b64encode(signature).decode("ascii"), settings.signing_key_id


def public_key_b64(settings: Settings) -> str:
    """The public half, base64, as served at `/api/public-keys`."""
    key = _load_private_key(str(settings.signing_key_file))
    return base64.b64encode(bytes(key.verify_key)).decode("ascii")


def verify_signature(hash_hex: str, signature_b64: str, public_key: str) -> bool:
    """Check a signature against a public key.

    Returns False on any failure - a bad signature, a malformed key, a hash that
    is not hex. Verification is called from a public route, so a malformed input
    must be a "no" rather than a 500 that reveals which part was malformed.
    """
    try:
        verify_key = signing.VerifyKey(base64.b64decode(public_key))
        verify_key.verify(bytes.fromhex(hash_hex), base64.b64decode(signature_b64))
        return True
    except (BadSignatureError, ValueError, TypeError):
        return False


def is_configured(settings: Settings) -> bool:
    """Whether this machine can sign. Used by `/api/health`."""
    try:
        _load_private_key(str(settings.signing_key_file))
        return True
    except SigningUnavailable:
        return False
