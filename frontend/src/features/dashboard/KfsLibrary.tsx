import { useCallback, useEffect, useState } from "react";
import { FileText } from "lucide-react";
import { getPublicKeys } from "@/lib/api";
import type { PublicKey } from "@/lib/types";
import { Card, ErrorNote, Pill } from "@/components/ui";

/**
 * The KFS library (build plan 12).
 *
 * Upload and Sarvam Document Intelligence extraction are **phase 11**, which is
 * a stretch goal. What is here now is what exists today: the three seeded
 * sample documents, and the signing keys that make a receipt's reference to one
 * of them verifiable.
 *
 * Stating that plainly beats an empty page with a spinner on it - and the
 * signing keys genuinely belong on a compliance screen.
 */
export function KfsLibrary() {
  const [keys, setKeys] = useState<PublicKey[]>([]);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(async () => {
    try {
      setKeys(await getPublicKeys());
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Could not load the signing keys.");
    }
  }, []);

  useEffect(() => {
    const timer = setTimeout(() => void load(), 0);
    return () => clearTimeout(timer);
  }, [load]);

  return (
    <div className="space-y-4 p-8">
      <header>
        <h1 className="text-text-1 text-2xl font-bold">KFS library</h1>
        <p className="text-text-3 mt-1 text-sm">
          Key Fact Statements, and the keys that make a receipt&rsquo;s reference to one checkable.
        </p>
      </header>

      {error && <ErrorNote message={error} onRetry={() => void load()} />}

      <Card
        title="Seeded documents"
        subtitle="Three SAMPLE-watermarked PDFs in the RBI format, generated by `make seed`"
      >
        <div className="space-y-2">
          {[
            { id: "offer_a", lender: "Partner NBFC A", version: "v3.2" },
            { id: "offer_b", lender: "Partner Bank B", version: "v2.8" },
            { id: "offer_c", lender: "Partner NBFC C", version: "v1.4" },
          ].map((document) => (
            <div
              key={document.id}
              className="flex items-center gap-3 rounded-lg border border-slate-200 px-4 py-3"
            >
              <FileText size={16} className="text-navy" aria-hidden />
              <div className="flex-1">
                <p className="text-text-1 text-[13px] font-semibold">
                  {document.lender} · {document.version}
                </p>
                <p className="text-text-3 text-[11.5px]">
                  Each document&rsquo;s SHA-256 is stored and is check #4 of receipt verification.
                </p>
              </div>
              <Pill tone="info">active</Pill>
            </div>
          ))}
        </div>
      </Card>

      <Card
        title="Signing keys"
        subtitle="Published at /api/public-keys so anyone can verify a receipt without us"
      >
        {keys.length === 0 ? (
          <p className="text-text-3 text-[12px]">
            No key registered yet. One is registered automatically with the first receipt.
          </p>
        ) : (
          <div className="space-y-2">
            {keys.map((key) => (
              <div key={key.keyId} className="flex items-center gap-3">
                <Pill tone={key.active ? "good" : "plain"}>
                  {key.active ? "active" : "retired"}
                </Pill>
                <span className="text-text-1 font-mono text-[12px] font-semibold">{key.keyId}</span>
                <span className="text-text-3 truncate font-mono text-[10.5px]">
                  {key.publicKeyB64}
                </span>
              </div>
            ))}
          </div>
        )}
        <p className="text-text-3 mt-3 text-[11.5px]">
          A retired key stays published, so receipts signed before a rotation keep verifying.
        </p>
      </Card>

      <Card title="Upload and extraction" subtitle="Phase 11, a stretch goal">
        <p className="text-text-2 text-[12.5px]">
          Uploading a lender&rsquo;s PDF and extracting its fields with Sarvam Document Intelligence
          is phase 11. The design point that matters is already settled:{" "}
          <strong>a human verifies the extracted fields before anything is published</strong>, and
          the generated teach-back questions pass the Number Guard before a customer sees them.
        </p>
      </Card>
    </div>
  );
}
